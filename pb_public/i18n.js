let lang = 'de';

const fill = (text, params) => text.replace(/\{(\w+)\}/g, (_, k) => (params[k] ?? ''));

// Translates a key; falls back to German, then to the key itself.
function t(key, params = {}) {
  return fill(I18N[lang][key] ?? I18N.de[key] ?? key, params);
}

// Translates a plural key ("singular|plural") for the count n.
function tn(key, n, params = {}) {
  const [one, many] = (I18N[lang][key] ?? I18N.de[key] ?? key).split('|');
  return fill(n === 1 ? one : (many ?? one), { ...params, n });
}

const hasTranslation = (key) => key in I18N[lang] || key in I18N.de;

// Applies translations to static markup: data-i18n (text), data-i18n-placeholder,
// data-i18n-title and data-i18n-aria (aria-label).
function translateStatic(root = document) {
  document.documentElement.lang = lang;
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
}
